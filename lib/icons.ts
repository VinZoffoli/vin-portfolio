/** Las marcas negras se pintan claras sobre fondo oscuro. */
export function hoverColor(hex: string) {
  const n = parseInt(hex.slice(1), 16);
  const lum = 0.2126 * ((n >> 16) & 255) + 0.7152 * ((n >> 8) & 255) + 0.0722 * (n & 255);
  return lum < 70 ? "#f6f3f0" : hex;
}
